// try/catch (audit 24/09) : stockage bloque (Firefox cookies bloques, certaines navigations privees) = SecurityError
// a la LECTURE, au chargement du module -> le site entier ne demarrait pas.
const readStored = (key) => {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
};
let current = LANGS.includes(readStored('lh_lang')) ? readStored('lh_lang') : 'en';

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANGS.includes(lang) || lang === current) return;
  current = lang;
  try {
    localStorage.setItem('lh_lang', lang);
  } catch {
    /* stockage indisponible (navigation privee) : le choix ne survit pas au rechargement, tant pis */
  }
  document.documentElement.lang = lang;
  applyStaticI18n();
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  window.dispatchEvent(new CustomEvent('lh:lang', { detail: { lang } }));
}

/** Traduction simple avec interpolation `{cle}`. */
export function t(key, vars) {
  const s = DICT[current]?.[key] ?? DICT.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_m, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Formate un ecart de temps relatif dans la langue courante (remplace le "il y a" FR / "ago" EN codes en dur). */
export function ago(iso) {
  const s = (Date.now() - new Date(iso).getTime()) / 1000;
  const n = s < 3600 ? Math.max(1, Math.round(s / 60)) : s < 86400 ? Math.round(s / 3600) : s < 45 * 86400 ? Math.round(s / 86400) : Math.round(s / (30 * 86400));
  const unit = s < 3600 ? t('ago.min') : s < 86400 ? t('ago.h') : s < 45 * 86400 ? t('ago.d') : t('ago.mo');
  if (current === 'fr') return `il y a ${n} ${unit}`;
  if (current === 'es') return `hace ${n} ${unit}`;
  return `${n} ${unit} ago`;
}

/** Applique les traductions aux elements statiques marques data-i18n / data-i18n-html dans le DOM. */
export function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  // Tooltip natif (attribut title) — ajoute pour le bouton "aller au pied de page" (Naim 22/09, 8e passe).
  root.querySelectorAll('[data-i18n-title]').forEach((el) => el.setAttribute('title', t(el.dataset.i18nTitle)));
  // Placeholder de champ — ajoute pour Liquid Enhancement (Naim 22/09).
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)));
}

